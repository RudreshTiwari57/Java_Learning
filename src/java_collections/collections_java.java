package java_collections;

//---------------------------------- What are Collections in Java?
//Collections in Java are containers that store multiple elements (objects). They are part of the Java Collections
// Framework (JCF) which provides ready-to-use data structures and algorithms (like sorting, searching, etc.).
//Think of collections as dynamic arrays, sets, maps, etc., that can grow and shrink automatically.

//----------------------------------------- Java Collections Framework: Main Interfaces

//        Interface	                Description	                            Example Classes
//        List	                    Ordered, duplicates allowed	            ArrayList, LinkedList
//        Set	                    Unordered, no duplicates allowed	    HashSet, LinkedHashSet, TreeSet
//        Queue	                    Follows FIFO order	                    LinkedList, PriorityQueue
//        Map	                    Key-value pairs	                        HashMap, TreeMap, LinkedHashMap


//--------------------------------------------- Hierarchy Overview (Core Interfaces)


//                                Collection (interface)
//                                ├── List
//                                │   ├── ArrayList
//                                │   └── LinkedList
//                                │
//                                ├── Set
//                                │   ├── HashSet
//                                │   ├── LinkedHashSet
//                                │   └── TreeSet
//                                │
//                                └── Queue
//                                    └── PriorityQueue
//
//                                Map (interface — not part of Collection)
//                                ├── HashMap
//                                ├── LinkedHashMap
//                                └── TreeMap

